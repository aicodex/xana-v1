import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/#token=browser-test-token')
  await expect(page.getByText('已连接', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '＋ 新建会话', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '本会话权限' })).toHaveValue('yolo')
})

async function send(page: import('@playwright/test').Page, text: string) {
  await page.getByRole('textbox', { name: '消息', exact: true }).fill(text)
  await page.getByRole('button', { name: /^(发送 ↑|排队 ↑)$/ }).click()
}

test('会话权限独立保存，审批刷新恢复，批准只执行一次', async ({ page }) => {
  const mode = page.getByRole('combobox', { name: '本会话权限' })
  await expect(mode).toHaveValue('yolo')
  const original = page.url()
  await mode.selectOption('manual')
  await send(page, 'write')
  await expect(page.getByRole('region', { name: '待审批操作' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: '单次批准', exact: true })).toBeVisible()
  await expect(mode).toHaveValue('manual')
  await page.getByRole('button', { name: '单次批准', exact: true }).click()
  await expect(page.getByText('完成：write', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '＋ 新建会话', exact: true }).click()
  await expect(mode).toHaveValue('yolo')
  await page.goto(original)
  await expect(mode).toHaveValue('manual')
  await expect(page.getByRole('button', { name: '单次批准', exact: true })).toHaveCount(0)
})

test('流式执行时可以插话、刷新、取消；中文输入法不会误发送', async ({ page }) => {
  await send(page, 'slow')
  await expect(page.getByText('处理中', { exact: true })).toBeVisible()
  const input = page.getByRole('textbox', { name: '消息', exact: true })
  await input.fill('输入法未完成')
  await input.dispatchEvent('keydown', { key: 'Enter', isComposing: true })
  await expect(input).toHaveValue('输入法未完成')
  await send(page, '补充要求')
  await expect(page.getByText('已排队 · 当前回答结束后处理', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('已排队 · 当前回答结束后处理', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '立即插话', exact: true }).click()
  await expect(page.getByText('已插话 · 等待当前步骤结束', { exact: true })).toBeVisible()
  await expect(page.getByText('处理中', { exact: true })).toBeVisible()
  const cancellation = page.waitForRequest(request => request.url().endsWith('/cancel') && request.method() === 'POST')
  await page.getByRole('button', { name: '■ 停止回答' }).click()
  expect((await cancellation).postDataJSON().run_id).toBeTruthy()
  await expect(page.getByRole('button', { name: '■ 停止回答' })).toHaveCount(0)
})

test('真实命令的运行日志可查看、下载，checklist 与 goal 可见', async ({ page }) => {
  await send(page, 'logs')
  await page.getByRole('group').filter({ hasText: 'Bash' }).first().getByText('工具调用').click()
  await page.getByRole('button', { name: '查看命令日志' }).first().click()
  await expect(page.getByTestId('command-log')).toContainText('browser-live-log')
  await expect(page.getByTestId('command-log')).toContainText('browser-log-done')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载完整日志' }).click()
  expect((await download).suggestedFilename()).toBe('command.log')
  await send(page, 'checklist')
  await expect(page.getByText('Checklist · 0/1')).toBeVisible()
  await page.getByRole('button', { name: '＋ 目标' }).click()
  await page.getByLabel('目标', { exact: true }).fill('goal-test')
  await page.getByRole('button', { name: '开始目标' }).click()
  await expect(page.getByText('已完成', { exact: true })).toBeVisible()
})

test('运行中子会话展示派发 prompt 与输出，关闭观察不停止任务', async ({ page }) => {
  await send(page, 'delegate')
  const task = page.locator('.task-open').first()
  await expect(task).toBeVisible()
  await task.click()
  const detail = page.locator('.detail-pane')
  await expect(detail.getByText('child_work', { exact: true })).toBeVisible()
  await expect(detail.getByText('子任务正在执行', { exact: true })).toBeVisible()
  await page.getByTitle('关闭详情').click()
  await expect(page.getByRole('button', { name: '停止任务' })).toBeVisible()
  await task.click()
  await expect(detail.getByText('子任务正在执行', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/workbench.png', fullPage: true })
  await page.getByRole('button', { name: '停止任务' }).click()
  await expect(page.getByRole('button', { name: '停止任务' })).toHaveCount(0)
})

test('多模态上传使用会话句柄；Markdown 脚本被过滤', async ({ page }) => {
  await page.getByLabel('添加图片或视频').setInputFiles({ name: 'sample.png', mimeType: 'image/png', buffer: Buffer.from('89504e470d0a1a0a' + '00'.repeat(32), 'hex') })
  await expect(page.getByRole('button', { name: 'sample.png ×' })).toBeVisible()
  await send(page, '这是什么图片')
  await expect(page.getByText('附件：图片', { exact: false })).toBeVisible()
  await send(page, '<img src=x onerror="window.xssExecuted=true">')
  await expect(page.getByText('完成：', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => (window as unknown as Record<string, unknown>).xssExecuted)).toBeUndefined()
})
