"""xana setup — first-time install bundle.

One command does all the bootstrap a fresh machine needs:

  1. write the seed ~/.xana/config/system.json (api keys go here, never the project);
  2. run `xana sync` to materialize ~/.xana/code/ and ~/.xana/mem/;
  3. drop executable launchers into ~/.xana/bin/ that load xana from
     ~/.xana/code/ at runtime (so they keep working across `xana sync` updates
     and don't care where the original source repo lives);
  4. append `export PATH="~/.xana/bin:$PATH"` to the user's shell rc (bash/zsh),
     inside a marker block so re-runs are idempotent.

Project-level .xana/ is deliberately NOT created: nothing user-specific
should live next to a project tree that might be committed.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import TextIO

from xana.cli.commands import sync as sync_cmd
from xana.config.loader import ensure_user_system_json, user_config_dir


_PATH_MARKER_BEGIN = "# >>> xana bin path >>>"
_PATH_MARKER_END = "# <<< xana bin path <<<"
_LAUNCHER_COMMANDS = ("xana", "xanac")


def add_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--no-wizard",
        action="store_true",
        help="skip the interactive model/channel wizard",
    )


def run(args: argparse.Namespace, *, out: TextIO) -> int:
    target_dir = user_config_dir()
    target_path = target_dir / "system.json"
    pre_existed = target_path.exists() and target_path.stat().st_size > 0
    user_path = ensure_user_system_json()
    print(f"[xana setup] user config dir   {target_dir}", file=out)
    print(f"  {'ready  ' if pre_existed else 'created'} {user_path.name}", file=out)

    print(file=out)
    sync_cmd.run(argparse.Namespace(source=None), out=out)

    bin_dir = sync_cmd.xana_home() / "bin"
    written, kept = _install_launchers(bin_dir)
    print(file=out)
    print(f"[xana setup] user bin dir      {bin_dir}", file=out)
    for p in written:
        print(f"  created {p.name}", file=out)
    for p in kept:
        print(f"  ready   {p.name}", file=out)

    rc, modified = _ensure_path_in_shell_rc(bin_dir)
    if rc is None:
        print("[xana setup] unknown shell — add the bin dir above to PATH manually", file=out)
    elif modified:
        print(f"[xana setup] PATH appended to {rc} — run: source {rc}", file=out)
    else:
        print(f"[xana setup] PATH already configured in {rc}", file=out)

    if not getattr(args, "no_wizard", False) and sys.stdin.isatty():
        from xana.cli.commands.setup_wizard import run_wizard
        print(file=out)
        return run_wizard(ask=input, out=out)
    return 0


def _install_launchers(bin_dir: Path) -> tuple[list[Path], list[Path]]:
    bin_dir.mkdir(parents=True, exist_ok=True)
    python_exe = sys.executable

    written: list[Path] = []
    kept: list[Path] = []
    for cmd in _LAUNCHER_COMMANDS:
        path = bin_dir / cmd
        body = _launcher_body(python_exe, cmd)
        if path.exists() and path.read_text(encoding="utf-8") == body:
            kept.append(path)
            continue
        path.write_text(body, encoding="utf-8")
        path.chmod(0o755)
        written.append(path)
    return written, kept


def _launcher_body(python_exe: str, cmd: str) -> str:
    """Self-contained Python launcher: resolves $XANA_HOME at runtime, points
    sys.path at ~/.xana/code/ (whatever the last `xana sync` produced), then
    dispatches to the CLI module's main(). No source-repo path is baked in,
    so the launcher keeps working after `xana sync` even if the original
    checkout was moved or deleted."""
    return (
        f"#!{python_exe}\n"
        f"# Auto-generated by `xana setup`. Re-run setup to refresh the shebang.\n"
        f"import os\n"
        f"import sys\n"
        f"from pathlib import Path\n"
        f'home = Path(os.environ.get("XANA_HOME") or (Path.home() / ".xana")).expanduser()\n'
        f'sys.path.insert(0, str(home / "code"))\n'
        f"from xana.cli.{cmd} import main\n"
        f"sys.exit(main())\n"
    )


def _ensure_path_in_shell_rc(bin_dir: Path) -> tuple[Path | None, bool]:
    shell = os.environ.get("SHELL", "")
    if shell.endswith("zsh"):
        rc = Path.home() / ".zshrc"
    elif shell.endswith("bash"):
        rc = Path.home() / ".bashrc"
    else:
        return (None, False)

    existing = rc.read_text(encoding="utf-8") if rc.exists() else ""
    if _PATH_MARKER_BEGIN in existing:
        return (rc, False)
    block = (
        f"\n{_PATH_MARKER_BEGIN}\n"
        f'export PATH="{bin_dir}:$PATH"\n'
        f"{_PATH_MARKER_END}\n"
    )
    rc.parent.mkdir(parents=True, exist_ok=True)
    with rc.open("a", encoding="utf-8") as f:
        f.write(block)
    return (rc, True)
