"""xana setup — initialize ~/.xana/config/system.json + install bin launchers.

Project-level .xana/ is deliberately NOT created: system.json holds API keys
and other secrets, and we keep that entirely user-level so nothing secret can
leak into a project tree that might be committed to git.

Three things happen on each `xana setup` run, all idempotent:

  1. write the seed system.json to ~/.xana/config/system.json if absent;
  2. drop executable Python launchers (xana, xanac) into ~/.xana/bin/ so
     the user can call them without remembering `python -m`;
  3. append `export PATH="$HOME/.xana/bin:$PATH"` to the shell rc file
     (bash / zsh) inside a marker block, exactly once.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import TextIO

import xana
from xana.config.loader import ensure_user_system_json, user_config_dir


_PATH_MARKER_BEGIN = "# >>> xana bin path >>>"
_PATH_MARKER_END = "# <<< xana bin path <<<"
_LAUNCHER_COMMANDS = ("xana", "xanac")


def add_arguments(parser: argparse.ArgumentParser) -> None:
    return None


def run(args: argparse.Namespace, *, out: TextIO) -> int:
    target_dir = user_config_dir()
    target_path = target_dir / "system.json"
    pre_existed = target_path.exists() and target_path.stat().st_size > 0
    user_path = ensure_user_system_json()
    print(f"[xana setup] user config dir   {target_dir}", file=out)
    print(f"  {'ready  ' if pre_existed else 'created'} {user_path.name}", file=out)

    bin_dir = _xana_home() / "bin"
    written, kept = _install_launchers(bin_dir)
    print(f"[xana setup] user bin dir      {bin_dir}", file=out)
    for p in written:
        print(f"  created {p.name}", file=out)
    for p in kept:
        print(f"  ready   {p.name}", file=out)

    rc, modified = _ensure_path_in_shell_rc(bin_dir)
    if rc is None:
        print("[xana setup] unknown shell — add the bin dir above to PATH manually", file=out)
    elif modified:
        print(f"[xana setup] PATH appended to {rc} — run: source {rc}", file=out)
    else:
        print(f"[xana setup] PATH already configured in {rc}", file=out)
    return 0


def _xana_home() -> Path:
    """Return $XANA_HOME (config dir's parent) or ~/.xana."""
    override = os.environ.get("XANA_HOME")
    if override:
        return Path(override).expanduser()
    return Path.home() / ".xana"


def _install_launchers(bin_dir: Path) -> tuple[list[Path], list[Path]]:
    bin_dir.mkdir(parents=True, exist_ok=True)
    xana_src_root = Path(xana.__file__).resolve().parent.parent
    python_exe = sys.executable

    written: list[Path] = []
    kept: list[Path] = []
    for cmd in _LAUNCHER_COMMANDS:
        path = bin_dir / cmd
        body = _launcher_body(python_exe, xana_src_root, cmd)
        if path.exists() and path.read_text(encoding="utf-8") == body:
            kept.append(path)
            continue
        path.write_text(body, encoding="utf-8")
        path.chmod(0o755)
        written.append(path)
    return written, kept


def _launcher_body(python_exe: str, xana_src_root: Path, cmd: str) -> str:
    """Tiny Python launcher: pin the interpreter, inject xana's src on
    sys.path so this works whether xana was pip-installed or run from a
    source checkout, then dispatch to the CLI module's main()."""
    return (
        f"#!{python_exe}\n"
        f"# Auto-generated by `xana setup`. Re-run setup to refresh paths.\n"
        f"import sys\n"
        f"sys.path.insert(0, {str(xana_src_root)!r})\n"
        f"from xana.cli.{cmd} import main\n"
        f"sys.exit(main())\n"
    )


def _ensure_path_in_shell_rc(bin_dir: Path) -> tuple[Path | None, bool]:
    """Append a PATH-export block to the user's shell rc if absent.

    Returns (rc_path, was_modified). rc_path is None when we don't know how
    to edit the user's shell (anything other than bash/zsh).
    """
    shell = os.environ.get("SHELL", "")
    if shell.endswith("zsh"):
        rc = Path.home() / ".zshrc"
    elif shell.endswith("bash"):
        rc = Path.home() / ".bashrc"
    else:
        return (None, False)

    existing = rc.read_text(encoding="utf-8") if rc.exists() else ""
    if _PATH_MARKER_BEGIN in existing:
        return (rc, False)
    block = (
        f"\n{_PATH_MARKER_BEGIN}\n"
        f'export PATH="{bin_dir}:$PATH"\n'
        f"{_PATH_MARKER_END}\n"
    )
    rc.parent.mkdir(parents=True, exist_ok=True)
    with rc.open("a", encoding="utf-8") as f:
        f.write(block)
    return (rc, True)
